export const LANGUAGE_KEY = 'workflow-language';
export function normalizePreference(value) { return ['zh','en'].includes(value) ? value : 'auto'; }
export function resolveLanguage(preference, languages = []) {
  if (['zh','en'].includes(preference)) return preference;
  return /^zh(?:-|_|$)/i.test(languages[0] || '') ? 'zh' : 'en';
}
export function readPreference(storage) { try { return normalizePreference(storage?.getItem(LANGUAGE_KEY)); } catch { return 'auto'; } }
export function savePreference(storage, preference) { try { storage?.setItem(LANGUAGE_KEY, normalizePreference(preference)); } catch {} }
